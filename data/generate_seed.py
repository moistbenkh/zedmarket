# ---- orders / items / payments ----
# seasonal weights by month: Nov/Dec peak, Jan dip, mild Aug-Sep bump
mw={1:0.7,2:0.8,3:0.9,4:0.9,5:1.0,6:1.0,7:1.0,8:1.2,9:1.2,10:1.3,11:2.2,12:2.6}
days=[START+dt.timedelta(days=d) for d in range(365)]
dweights=[mw[d.month] for d in days]
# lapsed customers: last 8 regular customers only order before mid-July
lapsed=set(range(NC-7,NC+1))
regular=[c for c in custs if c>2]
pw=[random.choice([1,1,2,3,5]) for _ in regular]          # a few heavy buyers, many one-timers
pmap=dict(zip(regular,pw))
pweights=[w for w in [p.__getitem__ if False else 0 for p in []]] or None
prod_w=[p[5] for p in prods]
NO=160
orders=[];items=[];pays=[]
oi=0;pid=0
stock=[p[3] for p in prods]
for oid in range(1,NO+1):
    cid=random.choices(regular,weights=[pmap[c] for c in regular])[0]
    d=random.choices(days,weights=dweights)[0]+dt.timedelta(hours=random.randint(7,21),minutes=random.randint(0,59))
    if cid in lapsed and d>TODAY-dt.timedelta(days=100):
        d=START+dt.timedelta(days=random.randint(0,230))+dt.timedelta(hours=10)
    age=(TODAY-d).days
    r=random.random()
    if age<=3 and r<0.8: st='placed'
    elif age<=10 and r<0.75: st=random.choice(['paid','shipped'])
    elif age<=21 and r<0.4: st='shipped'
    elif r<0.07: st='cancelled'
    elif r<0.11: st='refunded'
    elif r<0.14 and age<=30: st='placed'
    else: st='delivered'
    if oid>=NO-2:   # three open carts, created in the last week
        st='cart'; d=TODAY-dt.timedelta(days=random.randint(1,6),hours=random.randint(0,8))
        if cid in lapsed: cid=random.choice([c for c in regular if c not in lapsed])
    n=random.choices([1,2,3,4],weights=[45,30,18,7])[0]
    chosen=[];
    while len(chosen)<n:
        p=random.choices(range(1,len(prods)+1),weights=prod_w)[0]
        if p not in chosen: chosen.append(p)
    # frequently-bought-together pairing
    if random.random()<0.25 and 8 in chosen and 10 not in chosen: chosen.append(10)
    total=0
    for p in chosen:
        pr=prods[p-1][2]; qty=random.choices([1,2,3],weights=[70,22,8])[0] if pr<1000 else 1
        oi+=1; total+=pr*qty
        items.append((oi,oid,p,qty,pr))
    a=random.choice(addr[cid])
    orders.append((oid,cid,a,d,st,total))
    if st!='cart':
        m=random.choices(['mobile_money','card','bank_transfer','cash_on_delivery'],weights=[55,20,10,15])[0]
        failed=random.random()<0.07 and st in('cancelled','placed')
        if failed:
            pid+=1; pays.append((pid,oid,m,'failed',total,None))
            if st=='placed':   # customer retried and succeeded? keep as unpaid placed order
                pass
        elif st=='placed':
            pid+=1; pays.append((pid,oid,m,'pending',total,None))
        elif st=='cancelled':
            pid+=1; pays.append((pid,oid,m,'failed',total,None))
        elif st=='refunded':
            pid+=1; pays.append((pid,oid,m,'refunded',total,d+dt.timedelta(hours=2)))

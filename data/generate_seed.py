"""Generates sql/02_seed.sql (MySQL 8) with fictional, internally consistent data.
Run:  python3 data/generate_seed.py   (fixed random seed, so output is repeatable)
The data is identical to the earlier PostgreSQL build (same random sequence); only the SQL dialect and the
password hashes changed. Passwords are salted PBKDF2-SHA256 hashes, the format the Cloudflare Worker verifies:
    pbkdf2_sha256$<iterations>$<salt, base64>$<hash, base64>
Every seeded account has the demo password below; change it with  DEMO_PASSWORD=... python3 data/generate_seed.py"""
import random, datetime as dt, hashlib, base64, os
DEMO_PASSWORD = os.environ.get("DEMO_PASSWORD", "Demo#2026")
ITERATIONS = 100000          # the maximum the Workers runtime allows for PBKDF2
def pbkdf2_hash(password, cid):
    salt = hashlib.sha256(f"zed-market-salt-{cid}".encode()).digest()[:16]      # fixed salt per account keeps the seed repeatable
    dk = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS, dklen=32)
    return "pbkdf2_sha256$%d$%s$%s" % (ITERATIONS, base64.b64encode(salt).decode(), base64.b64encode(dk).decode())
random.seed(2026)
TODAY = dt.datetime(2026, 10, 18)
START = TODAY - dt.timedelta(days=365)

def q(s): return "'" + str(s).replace("'", "''") + "'"
out = ["-- 02_seed.sql : fictional data, generated by data/generate_seed.py (MySQL 8)", "START TRANSACTION;"]


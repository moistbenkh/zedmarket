# ---- addresses (1 per customer, a few have 2) ----
out.append("INSERT INTO addresses (address_id,customer_id,street,city,province,country,is_default) VALUES")
rows=[]; addr={}; aid=0
cw=[c[2] for c in cities]
for cid in custs:
    city,prov,_=random.choices(cities,weights=cw)[0]
    aid+=1; addr.setdefault(cid,[]).append(aid)
    rows.append(f"({aid},{cid},{q(str(random.randint(1,400))+' '+random.choice(streets))},{q(city)},{q(prov)},'Zambia',TRUE)")
    if random.random()<0.15:
        aid+=1; addr[cid].append(aid)
        c2,p2,_=random.choice(cities)
        rows.append(f"({aid},{cid},{q(str(random.randint(1,400))+' '+random.choice(streets))},{q(c2)},{q(p2)},'Zambia',FALSE)")

comments=['Works as described','Good value for money','Arrived quickly','Quality could be better','Would buy again','Stopped working after a month','Exactly what I needed','Packaging was damaged']
for a,oid,p,qty,pr in items:
    o=ordmap[oid]
    if o[4]=='delivered' and (p,o[1]) not in seen and random.random()<0.35:
        seen.add((p,o[1]))
        base=rating_bias.get(p,4.1)
        rt=max(1,min(5,round(random.gauss(base,0.9))))
        rev.append((len(rev)+1,p,o[1],rt,random.choice(comments),o[3]+dt.timedelta(days=random.randint(3,14))))
out.append("INSERT INTO reviews (review_id,product_id,customer_id,rating,comment,created_at) VALUES")
out.append(",\n".join(f"({a},{b},{c},{d},{q(e)},{q(f.strftime('%Y-%m-%d %H:%M:%S'))})" for a,b,c,d,e,f in rev)+";")

# MySQL advances AUTO_INCREMENT past the highest explicit id by itself, so no sequence fix-up is needed.
out.append("COMMIT;")
